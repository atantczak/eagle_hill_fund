# ruff: noqa: E501  (the system prompt is prose; keep its lines readable)
"""Optional Claude narrative over the structured snapshot.

The model never computes anything: it ranks, explains, and says what is noise.
Everything it is allowed to cite is in the JSON payload it receives. If the key
is missing or the call fails, the report ships without a narrative.

The narrative is markdown with a fixed set of ``##`` headings (``NARRATIVE_SECTIONS``)
so the renderers can place each part: the "one idea" section becomes its own
highlighted card in the HTML / PDF / email.
"""

from __future__ import annotations

import json
import logging
import re
from typing import Any, cast

from ehf.research.reporting.config import ReportConfig

log = logging.getLogger(__name__)

# (key, exact heading the model must use). Order = order in the report.
NARRATIVE_SECTIONS: tuple[tuple[str, str], ...] = (
    ("market_read", "Market read"),
    ("top_ideas", "Top ideas"),
    ("screen_notes", "Screen notes"),
    ("noise", "Noise and caveats"),
    ("idea", "One idea to chew on"),
)
IDEA_KEY = "idea"

# Rendered by the templates under the idea card. The model is told NOT to add its own.
IDEA_DISCLAIMER = (
    "A hypothesis generated by the research assistant from the current snapshot. It is not "
    "investment advice and not a recommendation. It exists to start a line of inquiry: treat "
    "it as a thesis to validate or kill, never as a reason to trade."
)

# Stable across days -> cacheable prefix. Volatile content goes in the user turn.
SYSTEM_PROMPT = """You are the research assistant for Eagle Hill Fund, a small, quantitatively minded fund run by one person. Every morning you receive a JSON snapshot: market context plus the output of six screens over the liquid US equity universe. Your job is to turn it into a short, opinionated read that a busy PM can act on in ten minutes, and to leave them with one genuinely thought-provoking idea to research.

What the screens mean (the numbers were computed deterministically; trust them, do not recompute):
- quality_dislocation: stock fell hard (21d return or 63d drawdown) but Piotroski / Altman / FCF yield / ROIC / leverage say the business is fine. These are research prompts for a 1-3 month mean-reversion or accumulation thesis. The most important section.
- pead: just reported earnings; surprise and price reaction point the same way. Post-earnings drift is the best-documented short-horizon effect; long for beats, avoid or short for misses.
- insider_cluster: two or more insiders bought in the open market recently, or one very large purchase. Sales were ignored on purpose.
- analyst_revision: net upgrades or downgrades over a few days, plus price-target notes.
- breakout_52w: new 52-week high with strong 12-1 momentum and a volume confirmation. Trend following.
- outlier_move: statistically abnormal one-day moves. Mostly noise. Explain them using the news if present; do not recommend trading them unless another screen also fired.

Output: markdown with EXACTLY these five second-level headings, in this order, spelled exactly like this:

## Market read
3-5 sentences: regime, breadth, vol, curve, what matters this week (econ and earnings calendars). Say explicitly whether this is a day to add risk, hold, or reduce.

## Top ideas
At most five, ranked, as a numbered list. For each: ticker in bold, the thesis in two sentences, the one number that makes it interesting, what you would want to see before acting, and what would invalidate it. Prefer names where two screens agree. Flag any that report earnings within a week.

## Screen notes
One short paragraph per screen with anything notable not already covered, or "nothing notable" in one line. Keep it brief.

## Noise and caveats
What looks exciting but probably isn't, data gaps listed in warnings, and anything in the snapshot that contradicts your read.

## One idea to chew on
Exactly one idea, and it must NOT be one of the Top ideas restated. It is the thing a sharp PM would not have noticed on their own: a theme several screens hint at together, a divergence between the macro picture (curve, breadth, vol, sectors) and the single-name hits, a pair or basket (long X against short Y), a second-order consequence of this week's calendar, a place where the consensus read is probably wrong, or a quiet pattern in the insider / revision / breakout data. Be bold and specific; the PM will validate it, that is the point. It must be falsifiable. Use these bold labels, each starting its own paragraph:
**The idea.** Two or three sentences.
**Why now.** The evidence in today's snapshot, with the numbers.
**How to validate.** Three concrete steps the PM could do this week (what data to pull, what to compare, what the answer should look like if the idea is right).
**What kills it.** One or two conditions that would make you drop it.
**Expression.** How it would be expressed if it survived validation (long, short, pair, basket, or an options structure in concept), sized as a research position.
150-250 words for this section.

Rules:
1. Only cite numbers that appear in the payload. Never invent news, prices, or fundamentals. If the news list is empty for a mover, say the move is unexplained by the feed.
2. No disclaimers, no "not investment advice" boilerplate, no hedging filler, no emojis. The report template adds the disclaimer itself. Be direct and specific.
3. Target 600-900 words in total. Use the five headings above and nothing above them; use bullets and bold freely inside sections.
"""


def split_narrative(text: str | None) -> dict[str, str]:
    """Pure: split the narrative markdown into ``{section_key: body}`` by its ``##`` headings.

    Heading matching is case-insensitive and tolerant of trailing punctuation. Text before
    the first recognised heading (if any) is returned under ``"preamble"``; unknown headings
    are kept under ``"other"`` so nothing the model wrote is lost.
    """
    if not text:
        return {}
    by_heading = {h.lower(): k for k, h in NARRATIVE_SECTIONS}
    out: dict[str, list[str]] = {}
    current = "preamble"
    for line in text.splitlines():
        m = re.match(r"^\s{0,3}#{2,3}\s+(.+?)\s*[:.]?\s*$", line)
        if m:
            heading = re.sub(r"[*_`]", "", m.group(1)).strip().lower()
            current = by_heading.get(heading, "other")
            if current == "other":
                out.setdefault(current, []).append(f"### {m.group(1).strip()}")
            continue
        out.setdefault(current, []).append(line)
    return {k: "\n".join(v).strip() for k, v in out.items() if "\n".join(v).strip()}


def write_narrative(
    payload: dict[str, Any], cfg: ReportConfig, *, api_key: str | None = None
) -> str | None:
    """Return markdown, or ``None`` if the narrative could not be produced."""
    try:
        import anthropic
    except Exception:  # noqa: BLE001 - a broken dependency must not kill the report
        log.exception("anthropic SDK could not be imported; skipping narrative")
        return None

    client = anthropic.Anthropic(api_key=api_key) if api_key else anthropic.Anthropic()
    user_content = (
        f"Snapshot for {payload.get('run_date')} (data as of {payload.get('data_as_of')}):\n\n"
        + json.dumps(payload, sort_keys=True, default=str)
    )
    try:
        with client.beta.messages.stream(
            model=cfg.anthropic_model,
            max_tokens=16000,
            system=[
                {"type": "text", "text": SYSTEM_PROMPT, "cache_control": {"type": "ephemeral"}}
            ],
            messages=[{"role": "user", "content": user_content}],
            output_config=cast(Any, {"effort": cfg.narrative_effort}),
            betas=["server-side-fallback-2026-07-01"],
            fallbacks="default",
        ) as stream:
            msg = stream.get_final_message()
    except anthropic.AuthenticationError:
        log.error("anthropic: invalid or missing API key; skipping narrative")
        return None
    except anthropic.RateLimitError as exc:
        log.error("anthropic: rate limited (%s); skipping narrative", exc)
        return None
    except anthropic.APIStatusError as exc:
        log.error("anthropic: API error %s: %s; skipping narrative", exc.status_code, exc.message)
        return None
    except anthropic.APIConnectionError as exc:
        log.error("anthropic: connection error: %s; skipping narrative", exc)
        return None

    if msg.stop_reason == "refusal":
        detail = getattr(msg, "stop_details", None)
        log.error("anthropic: request refused (%s)", getattr(detail, "category", None))
        return None
    text = "".join(block.text for block in msg.content if block.type == "text").strip()
    if msg.stop_reason == "max_tokens":
        text += "\n\n_(narrative truncated at max_tokens)_"
    usage = msg.usage
    log.info(
        "narrative: model=%s in=%s cached=%s out=%s",
        msg.model,
        usage.input_tokens,
        getattr(usage, "cache_read_input_tokens", None),
        usage.output_tokens,
    )
    missing = [h for k, h in NARRATIVE_SECTIONS if k not in split_narrative(text)]
    if missing:
        log.warning("narrative: missing sections %s", missing)
    return text or None
